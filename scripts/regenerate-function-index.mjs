/**
 * Runs the ssjs-data function-index generator so _data/ssjs_functions.yml is never stale.
 *
 * This file deliberately contains NO catalog logic. The single implementation lives in
 * ssjs-data/scripts/generate-function-index.mjs, which writes ssjs.guide/_data/ssjs_functions.yml
 * from the same traversal that produces site-index.json. Copying it here would create a
 * second implementation to drift out of sync — the exact failure this hook exists to
 * prevent — so it is loaded and executed in place instead.
 *
 * A missing generator is a hard failure, not a warning: without it the artifact cannot be
 * proven fresh, and exiting 0 would silently allow a stale ssjs_functions.yml to be
 * committed. A standalone clone of ssjs.guide with no sibling ssjs-data therefore needs
 * SKIP_HOOKS=1 to commit.
 *
 * Run from the ssjs.guide repo root:
 *   node scripts/regenerate-function-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const GENERATOR = path.resolve(__dirname, '../../ssjs-data/scripts/generate-function-index.mjs');

if (!fs.existsSync(GENERATOR)) {
  console.error('[PRE-COMMIT] ❌ Cannot find the function-index generator at:');
  console.error(`[PRE-COMMIT]    ${GENERATOR}`);
  console.error('[PRE-COMMIT]    _data/ssjs_functions.yml is generated by ssjs-data — it is never');
  console.error('[PRE-COMMIT]    built here, so there is nothing to fall back to.');
  console.error('[PRE-COMMIT]    Fix: clone ssjs-data next to ssjs.guide, or update the path in');
  console.error('[PRE-COMMIT]    this script if the generator moved. Do NOT copy the generator');
  console.error('[PRE-COMMIT]    into this repo — it must stay single-sourced in ssjs-data.');
  process.exit(1);
}

// The generator is a top-level side-effect script: it writes the YAML and calls
// process.exit(1) itself on failure. Any other failure surfaces as a rejected import,
// which exits non-zero — either way the commit is blocked.
await import(pathToFileURL(GENERATOR));
