/**
 * Runs the ssjs-data site-index generator so ssjs.guide/site-index.json is never stale.
 *
 * This file deliberately contains NO index-building logic. The single implementation
 * lives in ssjs-data/scripts/generate-site-index.mjs, which already writes both
 * ssjs-data/dist/site-index.json and ssjs.guide/site-index.json. Copying it here would
 * create a second implementation to drift out of sync — the exact failure this hook
 * exists to prevent — so it is loaded and executed in place instead.
 *
 * The generator also validates every generated URL and heading anchor against the real
 * pages in this repo and exits non-zero on a mismatch, so a renamed page without a
 * matching ssjs-data/src/urls.js update blocks the commit.
 *
 * A missing generator is a hard failure, not a warning: without it the artifact cannot
 * be proven fresh, and exiting 0 would silently allow a stale site-index.json to be
 * committed. A standalone clone of ssjs.guide with no sibling ssjs-data therefore needs
 * SKIP_HOOKS=1 to commit.
 *
 * Run from the ssjs.guide repo root:
 *   node scripts/regenerate-site-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const GENERATOR = path.resolve(__dirname, '../../ssjs-data/scripts/generate-site-index.mjs');

if (!fs.existsSync(GENERATOR)) {
  console.error('[PRE-COMMIT] ❌ Cannot find the site-index generator at:');
  console.error(`[PRE-COMMIT]    ${GENERATOR}`);
  console.error('[PRE-COMMIT]    site-index.json is generated by ssjs-data — it is never built');
  console.error('[PRE-COMMIT]    here, so there is nothing to fall back to.');
  console.error('[PRE-COMMIT]    Fix: clone ssjs-data next to ssjs.guide, or update the path in');
  console.error('[PRE-COMMIT]    this script if the generator moved. Do NOT copy the generator');
  console.error('[PRE-COMMIT]    into this repo — it must stay single-sourced in ssjs-data.');
  process.exit(1);
}

// The generator is a top-level side-effect script: it writes both copies of the index
// and calls process.exit(1) itself when URL validation fails. Any other failure surfaces
// as a rejected import, which exits non-zero — either way the commit is blocked.
await import(pathToFileURL(GENERATOR));
